"""Build the recorded-run file the Space and the demo replay.

Every output in the file is a real generation copied from the eval-logs
repo: the held-out compare (``predictions_*.jsonl`` next to
``curated/test``) and the hostile run (``hostile/predictions_*.jsonl``).
Nothing is generated here, and no model is loaded.

    python scripts/build_recording.py --eval-logs path/to/schemasmith-eval-logs
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from schemasmith.hostile import TICKETS, gate_decision
from schemasmith.hostile.score import score_row
from schemasmith.space_demo import RECORDED_PATH

HELD_OUT_IDS = ("T-100129", "T-100134", "T-100089")
HOSTILE_IDS = ("T-HX01", "T-HX05", "T-HX04", "T-HX17", "T-HX22")
SYSTEMS = ("base", "sft", "dpo")


def _jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def build(eval_logs: Path) -> dict:
    from schemasmith.contract.validator import score_output

    entries = []
    test = _jsonl(eval_logs / "curated" / "test" / "sft_alpaca.jsonl")
    held = {s: {r["id"]: r for r in _jsonl(eval_logs / f"predictions_{s}.jsonl")} for s in SYSTEMS}
    for row in test:
        gold = json.loads(row["output"])
        if gold["ticket_id"] not in HELD_OUT_IDS:
            continue
        runs = {}
        for s in SYSTEMS:
            out = held[s][gold["ticket_id"]]["output"]
            sc = score_output(out, gold, row["input"])
            decision, reasons = gate_decision(out, row["input"])
            runs[s] = {
                "output": out,
                "seconds": None,
                "contract_valid": sc.schema_valid,
                "unsupported": sc.unsupported_fields,
                "gate": decision,
                "gate_reasons": reasons,
            }
        entries.append(
            {
                "set": "held-out",
                "id": gold["ticket_id"],
                "text": row["input"],
                "gold": gold,
                "runs": runs,
            }
        )
    hostile = {
        s: {r["id"]: r for r in _jsonl(eval_logs / "hostile" / f"predictions_{s}.jsonl")}
        for s in SYSTEMS
    }
    for ticket in TICKETS:
        if ticket.ticket_id not in HOSTILE_IDS:
            continue
        runs = {}
        for s in SYSTEMS:
            rec = hostile[s][ticket.ticket_id]
            sc = score_row(ticket, rec["output"])
            runs[s] = {
                "output": rec["output"],
                "seconds": rec.get("seconds"),
                "contract_valid": sc["schema_valid"],
                "unsupported": sc["unsupported_fields"],
                "injection_followed": sc["injection_followed"],
                "gate": sc["gate"],
                "gate_reasons": sc["gate_reasons"],
            }
        entries.append(
            {
                "set": "hostile, " + ticket.kind.replace("_", " "),
                "id": ticket.ticket_id,
                "text": ticket.text,
                "gold": ticket.gold,
                "note": ticket.note,
                "runs": runs,
            }
        )
    order = {tid: i for i, tid in enumerate(HELD_OUT_IDS + HOSTILE_IDS)}
    entries.sort(key=lambda e: order[e["id"]])
    return {
        "source": "nightmoose/schemasmith-eval-logs (held-out compare and hostile/)",
        "note": "Real greedy generations: Tiny Aya Global, the SFT adapter, the DPO adapter.",
        "entries": entries,
    }


LABELS = {"base": "Base Tiny Aya Global", "sft": "SFT adapter", "dpo": "DPO adapter (final)"}


def transcript_markdown(payload: dict) -> str:
    """A readable transcript of the recorded run. Outputs are copied verbatim."""
    lines = [
        "# Recorded run transcript",
        "",
        "Real greedy generations, copied verbatim from the private eval-logs repo",
        "(`predictions_*.jsonl` for held-out tickets, `hostile/predictions_*.jsonl` for",
        "hostile ones). Generated by `scripts/build_recording.py`; do not edit by hand.",
        "Seconds are wall-clock generate time on one L4 GPU, one ticket at a time; the",
        "held-out run did not record them.",
        "",
    ]
    for entry in payload["entries"]:
        lines += [f"## {entry['id']} ({entry['set']})", ""]
        if entry.get("note"):
            lines += [entry["note"], ""]
        lines += ["Ticket:", "", "```text", entry["text"].strip(), "```", ""]
        for name, run in entry["runs"].items():
            secs = f", {run['seconds']:.2f} s" if run.get("seconds") else ""
            verdict = "contract-valid" if run["contract_valid"] else "fails the contract"
            made_up = ", ".join(run["unsupported"]) or "none"
            lines.append(
                f"**{LABELS[name]}**{secs}: {verdict}; values not in the ticket: {made_up}; "
                f"code gate: {run['gate']}."
            )
            if run.get("injection_followed"):
                lines.append("It wrote a value the injected instruction asked for.")
            lines += ["", "````text", run["output"].strip(), "````", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--eval-logs", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=RECORDED_PATH)
    parser.add_argument("--transcript", type=Path, default=Path("docs/demo_transcript.md"))
    args = parser.parse_args()
    payload = build(args.eval_logs)
    args.out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    args.transcript.write_text(transcript_markdown(payload), encoding="utf-8")
    print(f"wrote {len(payload['entries'])} recorded tickets to {args.out} and {args.transcript}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
